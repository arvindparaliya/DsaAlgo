package com.arvind;

public class Main {
    public static void main(String[] args) {

        //primitive datatype start with Lowercase
        //primitive means we cannot break further anymore8 primitive datatype
        //In java we have total

        byte bt = 10; // 1-byte
        short st = 1000; //2-byte
        int a = 10; // 4- byte
        boolean b = true; // for true and false => 1-bit
        float marks = 99.2f; //for decimal numbers => 4-byte
        double d = 997734726429.66663; //for longest decimal numbers => 8-byte
        long l = 5636343543535L; // 8-byte
        char c = 'c'; // 2-byte

        //Non-primitive datatype start with Capital later
        //What's the meaning of Non-primitive ?
        //non-primitive means we can break further anymore
        //e.g.,  String, Arrays , Classes, Interfaces, Enums
        String name = "Rahul"; //here we can break "Rahul" further into character like, 'R', 'a'.

    }
}
